#!/usr/bin/env python3
"""Compile single xnu sources locally with the flags a CI build recorded.

  river-cc.py BUILDTREE [-DX=Y ...] [-E|-S|-fsyntax-only] FILE ...

BUILDTREE is an extracted xnu-buildtree artifact (build/, xnu/, fakeroot/,
sdk-kernel-platform/); FILE is relative to BUILDTREE/xnu. Each component's
.CFLAGS/.CXXFLAGS/.SFLAGS file under build/xnu.obj/<config>/<comp>/DEVELOPMENT
records the complete CI compiler command line. CI paths are rewritten to the
local tree; extra -D/-U options are appended, e.g. -DRIVER=1 for
MACHINE_CONFIG=RIVER, whose only compiler-flag difference from SWEET it is.

The default is a real object compile into a scratch directory, so inline
assembly and system-register names are checked by the assembler too. The
local clang is newer than the CI's Xcode 15 clang; warnings are suppressed
and a pass here does not replace a CI build and link.
"""
import glob, os, subprocess, sys, tempfile

CI = '/Users/runner/work/ios-topaz/ios-topaz'


def tokens(line):
    """Split a recorded make command; -DX=((a * b) / c) keeps its spaces."""
    out, depth = [], 0
    for word in line.split():
        if depth:
            out[-1] += ' ' + word
        else:
            out.append(word)
        depth += word.count('(') - word.count(')')
    return out


def sync_exported_headers(bt):
    """Components include EXPORT_HDRS copies of headers such as SWEET.h, not
    the source tree: refresh any copy whose source was edited after it."""
    export = os.path.join(bt, 'build/xnu.obj/EXPORT_HDRS')
    for root, _, files in os.walk(export):
        for name in files:
            copy = os.path.join(root, name)
            src = os.path.join(bt, 'xnu', os.path.relpath(copy, export))
            if os.path.isfile(src) and os.path.getmtime(src) > os.path.getmtime(copy):
                os.remove(copy)  # installed read-only
                with open(src, 'rb') as f, open(copy, 'wb') as g:
                    g.write(f.read())
                print('sync', os.path.relpath(src, bt))


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    bt = os.path.abspath(argv[0])
    cfg = sorted(glob.glob(os.path.join(bt, 'build/xnu.obj/DEVELOPMENT_ARM64_*')))[0]
    cc = os.environ.get('RIVER_CC') or subprocess.run(
        ['xcrun', '-find', 'clang'], capture_output=True, text=True, check=True).stdout.strip()
    out = os.environ.get('RIVER_CC_OUT') or tempfile.mkdtemp(prefix='river-cc-')
    os.makedirs(out, exist_ok=True)
    sync_exported_headers(bt)
    # Generated by the CI build but outside the recorded include paths.
    extra, mode, rc = ['-idirafter', os.path.join(bt, 'build/xnu.obj/bsd')], ['-c'], 0
    for arg in argv[1:]:
        if arg.startswith(('-D', '-U')):
            extra.append(arg)
            continue
        if arg in ('-E', '-S', '-fsyntax-only'):
            mode = [arg]
            continue
        comp = arg.split('/', 1)[0]
        directory = os.path.join(cfg, comp, 'DEVELOPMENT')
        kind = '.CXXFLAGS' if arg.endswith('.cpp') else '.SFLAGS' if arg.endswith(('.s', '.S')) else '.CFLAGS'
        args = []
        for t in tokens(open(os.path.join(directory, kind)).read().replace('\0', ' '))[1:]:
            t = t.replace(CI + '/dxb/', bt + '/')
            if t.startswith('-I/Applications/Xcode') and t.endswith('PrivateHeaders/platform'):
                t = '-I' + os.path.join(bt, 'sdk-kernel-platform/platform')
            args.append(t)
        obj = os.path.join(out, os.path.basename(arg) + ('.i' if mode == ['-E'] else '.o'))
        cmd = [cc] + args + extra + ['-w'] + mode + [os.path.join(bt, 'xnu', arg)]
        if mode != ['-fsyntax-only']:
            cmd += ['-o', obj]
        if subprocess.run(cmd, cwd=directory).returncode == 0:
            print('ok  ', arg, obj if mode != ['-fsyntax-only'] else '')
        else:
            print('FAIL', arg, file=sys.stderr)
            rc = 1
    return rc


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
